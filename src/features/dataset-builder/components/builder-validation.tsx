"use client";

import {
    DatasetValidationIssue,
} from "../types/dataset-builder";

interface Props {

    issues: DatasetValidationIssue[];

}

export function BuilderValidation({

    issues,

}: Props) {

    return (

        <div
            className="
                rounded-xl
                border
                p-6
                space-y-6
            "
        >

            <div>

                <h2
                    className="
                        text-xl
                        font-semibold
                    "
                >

                    Dataset Validation

                </h2>

                <p
                    className="
                        text-sm
                        text-muted-foreground
                    "
                >

                    Validation results generated by the builder.

                </p>

            </div>

            {

                issues.length === 0 && (

                    <div
                        className="
                            rounded-lg
                            border
                            p-6
                            text-center
                            text-muted-foreground
                        "
                    >

                        No validation issues found.

                    </div>

                )

            }

            {

                issues.map(

                    (

                        issue,

                        index,

                    ) => (

                        <div

                            key={`${issue.type}-${index}`}

                            className="
                                rounded-lg
                                border
                                p-4
                                space-y-3
                            "

                        >

                            <div
                                className="
                                    flex
                                    items-center
                                    justify-between
                                "
                            >

                                <h3
                                    className="
                                        font-semibold
                                    "
                                >

                                    {issue.type}

                                </h3>

                                <span
                                    className="
                                        rounded
                                        border
                                        px-2
                                        py-1
                                        text-xs
                                        uppercase
                                    "
                                >

                                    {issue.severity}

                                </span>

                            </div>

                            <p
                                className="
                                    text-sm
                                    text-muted-foreground
                                "
                            >

                                {issue.message}

                            </p>

                            <div
                                className="
                                    text-sm
                                "
                            >

                                <strong>

                                    Affected Records:

                                </strong>

                                {" "}

                                {issue.affected_records}

                            </div>

                        </div>

                    )

                )

            }

        </div>

    );

}